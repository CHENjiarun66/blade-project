  `chat_schema_hash` binary(32) DEFAULT NULL COMMENT 'ChatStorage schema SHA-256',
  `contact_schema_hash` binary(32) DEFAULT NULL COMMENT 'Contacts schema SHA-256',
  `status` varchar(20) NOT NULL COMMENT '状态: RUNNING/SUCCEEDED/PARTIAL/FAILED',
