CREATE TABLE `wa_message` (
  `id` bigint NOT NULL AUTO_INCREMENT COMMENT 'WhatsApp逻辑消息ID',
  `tenant_id` bigint NOT NULL COMMENT '租户ID',
  `account_id` bigint NOT NULL COMMENT 'WhatsApp账号ID',
  `conversation_id` bigint NOT NULL COMMENT 'WhatsApp会话ID',
  `contact_id` bigint DEFAULT NULL COMMENT 'WhatsApp联系人ID',
  `external_message_id` varchar(191) DEFAULT NULL COMMENT 'WhatsApp stanza ID',
  `logical_key_hash` binary(32) NOT NULL COMMENT '版本化逻辑消息SHA-256键',
  `direction` varchar(12) NOT NULL COMMENT '方向: INBOUND/OUTBOUND/SYSTEM',
  `sender_jid` varchar(191) DEFAULT NULL COMMENT '发送方JID',
  `message_type` varchar(32) NOT NULL COMMENT '归一化消息类型',
  `source_message_type` int DEFAULT NULL COMMENT '源消息类型整数',
  `mapping_version` varchar(16) NOT NULL DEFAULT 'v1' COMMENT '类型和逻辑键映射版本',
  `text_content` longtext DEFAULT NULL COMMENT '文本或caption，受权限控制',
  `source_timestamp_ms` bigint NOT NULL COMMENT '源消息时间毫秒值',
  `sent_at` datetime(3) NOT NULL COMMENT '消息时间(UTC)',
  `status` varchar(20) DEFAULT NULL COMMENT '归一化源状态',
  `is_starred` tinyint NOT NULL DEFAULT 0 COMMENT '是否星标',
  `reply_to_external_id` varchar(191) DEFAULT NULL COMMENT '被回复消息外部ID',
  `reply_to_message_id` bigint DEFAULT NULL COMMENT '被回复逻辑消息ID',
  `content_hash` binary(32) DEFAULT NULL COMMENT '规范化内容SHA-256',
  `first_seen_batch_id` bigint NOT NULL COMMENT '首次观察批次ID',
  `last_seen_batch_id` bigint NOT NULL COMMENT '最近观察批次ID',
  `is_revoked` tinyint NOT NULL DEFAULT 0 COMMENT '是否已撤回',
  `revoked_at` datetime(3) DEFAULT NULL COMMENT '撤回观察时间(UTC)',
  `source_deleted` tinyint NOT NULL DEFAULT 0 COMMENT '源端删除事实',
  `raw_metadata` json DEFAULT NULL COMMENT '白名单消息源属性',
  `create_by` bigint DEFAULT NULL COMMENT '创建人ID',
  `create_time` datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '创建时间',
  `update_time` datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3) COMMENT '更新时间',
  `deleted` tinyint NOT NULL DEFAULT 0 COMMENT 'ERP隐藏标记: 0正常 1隐藏',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_wa_message_logical` (`tenant_id`, `account_id`, `logical_key_hash`),
  KEY `idx_wa_message_conversation` (`tenant_id`, `conversation_id`, `sent_at`, `id`),
  KEY `idx_wa_message_contact` (`tenant_id`, `contact_id`, `sent_at`, `id`),
  KEY `idx_wa_message_external` (`tenant_id`, `account_id`, `external_message_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='WhatsApp逻辑消息';

