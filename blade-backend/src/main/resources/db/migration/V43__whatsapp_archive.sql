CREATE TABLE `wa_account` (
  `id` bigint NOT NULL AUTO_INCREMENT COMMENT 'WhatsApp账号ID',
  `tenant_id` bigint NOT NULL COMMENT '租户ID',
  `source_type` varchar(20) NOT NULL COMMENT '数据源类型: MAC_APP/BUSINESS_PLATFORM',
  `account_jid` varchar(191) NOT NULL COMMENT '源账号JID',
  `phone_normalized` varchar(32) DEFAULT NULL COMMENT '标准化号码(E.164 digits-only)',
  `display_name` varchar(100) DEFAULT NULL COMMENT '账号显示名',
  `app_version` varchar(32) DEFAULT NULL COMMENT '源App版本',
  `source_instance_hash` binary(32) DEFAULT NULL COMMENT '源实例匿名SHA-256指纹',
  `last_success_batch_id` bigint DEFAULT NULL COMMENT '最近成功导入批次ID',
  `last_sync_time` datetime(3) DEFAULT NULL COMMENT '最近成功同步时间(UTC)',
  `status` tinyint NOT NULL DEFAULT 1 COMMENT '状态: 1启用 0停用',
  `create_by` bigint DEFAULT NULL COMMENT '创建人ID',
  `create_time` datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '创建时间',
  `update_time` datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3) COMMENT '更新时间',
  `deleted` tinyint NOT NULL DEFAULT 0 COMMENT '删除标记: 0正常 1删除',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_wa_account_source` (`tenant_id`, `source_type`, `account_jid`),
  KEY `idx_wa_account_status` (`tenant_id`, `status`, `deleted`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='WhatsApp数据源账号';

CREATE TABLE `wa_import_batch` (
  `id` bigint NOT NULL AUTO_INCREMENT COMMENT '导入批次ID',
